export const pickBin = (rowCount, rolls) => {
  if (Array.isArray(rolls)) {
    return rolls.reduce((sum, step) => sum + (step ? 1 : 0), 0);
  }
  let bin = 0;
  for (let i = 0; i < rowCount; i += 1) {
    if (Math.random() < 0.5) bin += 1;
  }
  return bin;
};
